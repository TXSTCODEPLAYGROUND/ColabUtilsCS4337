#!/usr/bin/env python3
"""Sync the Colab runtime snapshot from https://github.com/googlecolab/backend-info.

Writes:
  constraints/colab-pip-freeze.gpu.txt  raw copy of Colab's GPU pip freeze (for diffs)
  constraints/colab-os-info.gpu.txt     raw copy of Colab's GPU OS / Python info
  constraints/colab-gpu.txt             pip constraints usable on any Linux/macOS runner
  src/colabutilscs4337/_tested.json     versions shipped with the package for env.check()

Usage:
  python scripts/sync_colab_runtime.py           # update files
  python scripts/sync_colab_runtime.py --check   # exit 1 if Colab changed since last sync
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = "https://raw.githubusercontent.com/googlecolab/backend-info/main"
COMMITS_API = "https://api.github.com/repos/googlecolab/backend-info/commits?per_page=1&path="

FREEZE_FILE = ROOT / "constraints" / "colab-pip-freeze.gpu.txt"
OS_FILE = ROOT / "constraints" / "colab-os-info.gpu.txt"
CONSTRAINTS_FILE = ROOT / "constraints" / "colab-gpu.txt"
TESTED_FILE = ROOT / "src" / "colabutilscs4337" / "_tested.json"

sys.path.insert(0, str(ROOT / "src"))
from colabutilscs4337.env._runtime import EXTRAS, TRACKED  # noqa: E402

# Present in Colab's freeze but not installable from PyPI at that version.
NOT_ON_PYPI = {"google-colab", "python-apt", "dbus-python", "pygobject", "ufw", "screen-resize"}


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "colabutilscs4337-sync"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode()


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_freeze(text: str) -> dict[str, str]:
    """``{normalized_name: version}``; ``name @ url`` lines take the version from the wheel."""
    pkgs: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "==" in line:
            name, version = line.split("==", 1)
            pkgs[normalize(name)] = version.strip()
        elif " @ " in line:
            name, url = line.split(" @ ", 1)
            match = re.search(r"/[^/]+?-([0-9][^-/]*)-(?:cp|py)\d", url.replace("%2B", "+"))
            if match:
                pkgs[normalize(name)] = match.group(1)
    return pkgs


def build_constraints(pkgs: dict[str, str], source_note: str) -> str:
    lines = [
        "# Generated by scripts/sync_colab_runtime.py; do not edit by hand.",
        f"# Source: {source_note}",
        "# Local build tags (+cu130, +cpu) are stripped so CPU wheels satisfy them.",
    ]
    for name, version in sorted(pkgs.items()):
        if name in NOT_ON_PYPI:
            continue
        lines.append(f"{name}=={version.split('+', 1)[0]}")
    return "\n".join(lines) + "\n"


def parse_os_info(text: str) -> tuple[str | None, str | None]:
    lines = [ln.strip() for ln in text.splitlines() if ln.strip() and not ln.startswith("#")]
    os_name = lines[0] if lines else None
    python = next((ln.split()[1] for ln in lines if ln.startswith("Python ")), None)
    return os_name, python


def latest_commit(path: str) -> str | None:
    try:
        data = json.loads(fetch(COMMITS_API + path))
        return data[0]["sha"]
    except Exception:
        return None


def build_tested(
    pkgs: dict[str, str], os_name: str | None, python: str | None, commit: str | None
) -> dict:
    wanted = (*TRACKED, *EXTRAS)
    return {
        "source": "https://github.com/googlecolab/backend-info",
        "source_commit": commit,
        "runtime": "gpu",
        "os": os_name,
        "python": python,
        "packages": {d: pkgs[normalize(d)] for d in wanted if normalize(d) in pkgs},
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the snapshot is stale")
    args = parser.parse_args()

    freeze = fetch(f"{RAW}/pip-freeze.gpu.txt")
    os_info = fetch(f"{RAW}/os-info-gpu.txt")
    pkgs = parse_freeze(freeze)
    os_name, python = parse_os_info(os_info)

    stale = [
        p.relative_to(ROOT)
        for p, new in ((FREEZE_FILE, freeze), (OS_FILE, os_info))
        if not p.exists() or p.read_text() != new
    ]
    if args.check:
        if stale:
            print("Colab runtime changed since last sync:", ", ".join(map(str, stale)))
            return 1
        print("Colab runtime snapshot is up to date.")
        return 0

    commit = latest_commit("pip-freeze.gpu.txt")
    tested = build_tested(pkgs, os_name, python, commit)
    previous = json.loads(TESTED_FILE.read_text()) if TESTED_FILE.exists() else {}
    unchanged = {k: v for k, v in previous.items() if k != "synced_at"} == tested
    tested["synced_at"] = (
        previous.get("synced_at")
        if unchanged and previous.get("synced_at")
        else dt.date.today().isoformat()
    )

    CONSTRAINTS_FILE.parent.mkdir(parents=True, exist_ok=True)
    FREEZE_FILE.write_text(freeze)
    OS_FILE.write_text(os_info)
    CONSTRAINTS_FILE.write_text(build_constraints(pkgs, f"{RAW}/pip-freeze.gpu.txt"))
    TESTED_FILE.write_text(json.dumps(tested, indent=2) + "\n")

    print(f"Python {python}; {os_name}; {len(pkgs)} packages")
    for name, version in tested["packages"].items():
        print(f"  {name}=={version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
